def parse_facts(text):
    rows = []
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = [p.strip() for p in line.split("||")]
        if len(parts) != 6:
            raise SystemExit("facts列数 " + str(len(parts)) + ": " + line[:80])
        rows.append(tuple(parts))
    return rows


def check(items):
    problems = []
    if len(items) != 1000:
        problems.append("count=" + str(len(items)))
    ids = [q["id"] for q in items]
    if len(ids) != len(set(ids)):
        problems.append("id重複")
    banned = ["バンは狩猟鳥である", "ゴイサギは狩猟鳥である", "オシドリは狩猟鳥である", "カモシカは狩猟獣である", "休猟区の存続期間は3年を下らない"]
    for q in items:
        correct = q["choices"][q["answer"]]
        for word in banned:
            if word in correct and "ではない" not in correct and "除" not in correct and "入っていな" not in correct:
                problems.append(q["id"] + " " + word)
    counts = Counter(q["category"] for q in items)
    for cat, need in (("law", 13), ("manage", 2), ("wildlife", 9), ("gear", 6)):
        if counts[cat] < need:
            problems.append(cat + "が少ない")
