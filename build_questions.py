ITEMS = []
SEEN = set()


def add(cat, topic, text, correct, wrongs, explain, licenses="all", origin="practice"):
    wrongs = [w for w in dict.fromkeys(wrongs) if w and w != correct]
    if len(wrongs) < 2:
        raise SystemExit("選択肢不足: " + text)
    pair = wrongs[:2]
    if len(set(pair)) < 2:
        raise SystemExit("誤答が重複: " + text)
    key = "\n".join([text, correct, *sorted(pair)])
    if key in SEEN:
        return False
    SEEN.add(key)
    seed = int(hashlib.sha256(key.encode("utf-8")).hexdigest()[:8], 16)
    choices = [correct, pair[0], pair[1]]
    random.Random(seed).shuffle(choices)
    ITEMS.append({
        "id": "q" + hashlib.sha1(key.encode("utf-8")).hexdigest()[:10],
        "category": cat,
        "topic": topic,
        "licenses": LIC[licenses] if isinstance(licenses, str) else licenses,
        "text": text,
        "choices": choices,
        "answer": choices.index(correct),
        "explain": explain,
        "origin": origin,
    })
    return True


def add_pairs(rows):
    groups = defaultdict(list)
    trues, falses = set(), set()
    for row in rows:
        if len(row) != 6:
            raise SystemExit("列数: " + str(row))
        cat, topic, true, false, explain, lic = row
        if true in falses or false in trues or true == false:
            raise SystemExit("真偽が衝突: " + true[:40])
        trues.add(true)
        falses.add(false)
        groups[(cat, topic, lic)].append(row)
    for key, group in groups.items():
        if len(group) < 2:
            raise SystemExit("同じ項目が2行必要: " + str(key))
        cat, topic, lic = key
        for i, row in enumerate(group):
            other = group[(i + 1) % len(group)]
            true, false, explain = row[2], row[3], row[4]
            add(cat, topic, topic + "について、次のうち適切なものはどれか。", true, [false, other[3]], explain, lic, "statute")
            add(cat, topic, topic + "について、次のうち誤っているものはどれか。", false, [true, other[2]], explain, lic, "statute")


